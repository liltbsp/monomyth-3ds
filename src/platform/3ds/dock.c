#include <mgba/core/core.h>
#include <mgba-util/gui/font.h>

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* GBA key bit positions (match mGBA's GBA_KEY_* enum). */
enum {
	K_A = 0, K_B, K_SELECT, K_START, K_RIGHT, K_LEFT, K_UP, K_DOWN, K_R, K_L
};

#define DOCK_MAIN_BUTTONS 6
#define DOCK_SMALL_BUTTONS 4
#define DOCK_BUTTONS (DOCK_MAIN_BUTTONS + DOCK_SMALL_BUTTONS)
#define MAX_TOKENS 48
#define MAX_LABEL 16
#define MAX_MENU 12

#define PRESS_FRAMES 3
#define RELEASE_FRAMES 3

/* Colors are 0xAABBGGRR. Purple theme. */
#define COL_BG       0xFF1E1216
#define COL_HEADER   0xFF3D1C2A
#define COL_ACCENT   0xFFFF7CB0
#define COL_MAIN     0xFF9A3D6A
#define COL_MAIN_HI  0xFFD66B9B
#define COL_SMALL    0xFF48333A
#define COL_SMALL_HI 0xFF74525E
#define COL_TEXT     0xFFFFFFFF
#define COL_DIM      0x9FFFFFFF

enum TokenType { T_KEY, T_WAIT, T_MENU };

struct Token {
	enum TokenType type;
	int value; /* key bit, frame count, or action id */
};

struct DockButton {
	char label[MAX_LABEL];
	struct Token tokens[MAX_TOKENS];
	int nTokens;
	s16 x, y, w, h;
	bool small;
};

static struct DockButton buttons[DOCK_BUTTONS];
static struct GUIFont* dockFont;
static C3D_Tex whiteTex;
static bool whiteReady;

/* START menu memory (0 = unknown). */
static u32 cursorAddr, actionsAddr, countAddr;
/* Fallback when addresses are unknown: vanilla Emerald order. */
static const u8 fallbackMenu[] = { 0, 1, 2, 3, 4, 5, 6, 7 };
static int guessedCursor;

/* Macro runner state. */
static struct DockButton* running;
static int tokenIndex;
static int frameTimer;
static u16 heldNow;
/* Extra presses generated by an "@" token. */
static int pendingMoves;  /* >0 = DOWN presses, <0 = UP presses */
static int pressedButton = -1;
static int flashFrames;

static int _ieq(const char* a, const char* b) {
	while (*a && *b) {
		if (toupper((unsigned char) *a) != toupper((unsigned char) *b)) {
			return 0;
		}
		++a;
		++b;
	}
	return *a == *b;
}

static int _keyFromName(const char* s) {
	static const struct { const char* name; int bit; } names[] = {
		{ "A", K_A }, { "B", K_B }, { "SELECT", K_SELECT }, { "START", K_START },
		{ "RIGHT", K_RIGHT }, { "LEFT", K_LEFT }, { "UP", K_UP }, { "DOWN", K_DOWN },
		{ "R", K_R }, { "L", K_L },
	};
	size_t i;
	for (i = 0; i < sizeof(names) / sizeof(names[0]); ++i) {
		if (_ieq(s, names[i].name)) {
			return names[i].bit;
		}
	}
	return -1;
}

static void _parseMacro(struct DockButton* b, const char* text) {
	char buf[256];
	strncpy(buf, text, sizeof(buf) - 1);
	buf[sizeof(buf) - 1] = '\0';
	b->nTokens = 0;
	char* cur = buf;
	while (*cur && b->nTokens < MAX_TOKENS) {
		while (*cur == ',' || *cur == ' ' || *cur == '\t') {
			++cur;
		}
		if (!*cur) {
			break;
		}
		char* tok = cur;
		while (*cur && *cur != ',' && *cur != ' ' && *cur != '\t') {
			++cur;
		}
		if (*cur) {
			*cur++ = '\0';
		}
		struct Token* t = &b->tokens[b->nTokens];
		if ((tok[0] == 'W' || tok[0] == 'w') && isdigit((unsigned char) tok[1])) {
			t->type = T_WAIT;
			t->value = atoi(&tok[1]);
		} else if (tok[0] == '@' && isdigit((unsigned char) tok[1])) {
			t->type = T_MENU;
			t->value = atoi(&tok[1]);
		} else {
			int key = _keyFromName(tok);
			if (key < 0) {
				continue;
			}
			t->type = T_KEY;
			t->value = key;
		}
		++b->nTokens;
	}
}

static void _setButton(int i, const char* label, const char* macro) {
	strncpy(buttons[i].label, label, MAX_LABEL - 1);
	buttons[i].label[MAX_LABEL - 1] = '\0';
	_parseMacro(&buttons[i], macro);
}

static void _layout(void) {
	/* 3x2 grid of main buttons, then a row of 4 small ones. */
	const s16 gap = 6, top = 30, mainW = 100, mainH = 68;
	int i;
	for (i = 0; i < DOCK_MAIN_BUTTONS; ++i) {
		buttons[i].x = 7 + (i % 3) * (mainW + 3);
		buttons[i].y = top + (i / 3) * (mainH + gap);
		buttons[i].w = mainW;
		buttons[i].h = mainH;
		buttons[i].small = false;
	}
	const s16 smallW = 74, smallY = top + 2 * (mainH + gap) + 2, smallH = 50;
	for (i = 0; i < DOCK_SMALL_BUTTONS; ++i) {
		struct DockButton* b = &buttons[DOCK_MAIN_BUTTONS + i];
		b->x = 6 + i * (smallW + 4);
		b->y = smallY;
		b->w = smallW;
		b->h = smallH;
		b->small = true;
	}
}

static void _defaults(void) {
	/* Vanilla Emerald START menu action ids:
	 * 0 POKEDEX, 1 POKEMON, 2 BAG, 3 POKENAV, 4 PLAYER, 5 SAVE, 6 OPTION, 7 EXIT */
	_setButton(0, "PARTY", "START,W12,@1,A");
	_setButton(1, "BAG", "START,W12,@2,A");
	_setButton(2, "POKEDEX", "START,W12,@0,A");
	_setButton(3, "POKENAV", "START,W12,@3,A");
	_setButton(4, "CARD", "START,W12,@4,A");
	_setButton(5, "SAVE", "START,W12,@5,A");
	_setButton(6, "START", "START");
	_setButton(7, "SELECT", "SELECT");
	_setButton(8, "A", "A");
	_setButton(9, "B", "B");
	cursorAddr = actionsAddr = countAddr = 0;
}

static char* _trim(char* s) {
	while (isspace((unsigned char) *s)) {
		++s;
	}
	char* end = s + strlen(s);
	while (end > s && isspace((unsigned char) end[-1])) {
		--end;
	}
	*end = '\0';
	return s;
}

void dockLoadConfig(const char* path) {
	_defaults();
	FILE* f = fopen(path, "r");
	if (!f) {
		return;
	}
	char line[320];
	while (fgets(line, sizeof(line), f)) {
		char* s = _trim(line);
		if (!*s || *s == '#' || *s == ';' || *s == '[') {
			continue;
		}
		char* eq = strchr(s, '=');
		if (!eq) {
			continue;
		}
		*eq = '\0';
		char* key = _trim(s);
		char* value = _trim(eq + 1);
		int n;
		char field[16];
		if (sscanf(key, "button%d.%15s", &n, field) == 2 && n >= 1 && n <= DOCK_BUTTONS) {
			struct DockButton* b = &buttons[n - 1];
			if (_ieq(field, "label")) {
				strncpy(b->label, value, MAX_LABEL - 1);
				b->label[MAX_LABEL - 1] = '\0';
			} else if (_ieq(field, "macro")) {
				_parseMacro(b, value);
			}
		} else if (_ieq(key, "cursor_addr")) {
			cursorAddr = strtoul(value, NULL, 16);
		} else if (_ieq(key, "actions_addr")) {
			actionsAddr = strtoul(value, NULL, 16);
		} else if (_ieq(key, "count_addr")) {
			countAddr = strtoul(value, NULL, 16);
		}
	}
	fclose(f);
}

void dockInit(struct GUIFont* font) {
	dockFont = font;
	_layout();
	_defaults();
	if (C3D_TexInit(&whiteTex, 8, 8, GPU_RGBA8)) {
		memset(whiteTex.data, 0xFF, 8 * 8 * 4);
		GSPGPU_FlushDataCache(whiteTex.data, 8 * 8 * 4);
		whiteReady = true;
	}
	dockLoadConfig(DOCK_CONFIG_PATH);
}

void dockDeinit(void) {
	if (whiteReady) {
		C3D_TexDelete(&whiteTex);
		whiteReady = false;
	}
}

/* Work out how many DOWN (positive) or UP (negative) presses move the START
 * menu cursor onto the entry with the given action id. */
static int _menuMoves(struct mCore* core, int actionId) {
	u8 menu[MAX_MENU];
	int count, cursor;
	if (cursorAddr && actionsAddr && countAddr) {
		count = core->busRead8(core, countAddr);
		if (count <= 0 || count > MAX_MENU) {
			return 0;
		}
		int i;
		for (i = 0; i < count; ++i) {
			menu[i] = core->busRead8(core, actionsAddr + i);
		}
		cursor = core->busRead8(core, cursorAddr);
	} else {
		count = sizeof(fallbackMenu);
		memcpy(menu, fallbackMenu, count);
		cursor = guessedCursor;
	}
	int target = -1;
	int i;
	for (i = 0; i < count; ++i) {
		if (menu[i] == actionId) {
			target = i;
			break;
		}
	}
	if (target < 0 || cursor < 0 || cursor >= count) {
		return 0;
	}
	guessedCursor = target;
	int down = (target - cursor + count) % count;
	int up = count - down;
	return down <= up ? down : -up;
}

static void _startMacro(int index) {
	running = &buttons[index];
	tokenIndex = 0;
	frameTimer = 0;
	heldNow = 0;
	pendingMoves = 0;
	pressedButton = index;
	flashFrames = 8;
}

static int _hitTest(u16 px, u16 py) {
	int i;
	for (i = 0; i < DOCK_BUTTONS; ++i) {
		const struct DockButton* b = &buttons[i];
		if (b->nTokens && px >= b->x && px < b->x + b->w && py >= b->y && py < b->y + b->h) {
			return i;
		}
	}
	return -1;
}

/* Advance the macro by one frame and return the keys to hold. */
static u16 _stepMacro(struct mCore* core) {
	if (frameTimer > 0) {
		--frameTimer;
		return heldNow;
	}
	/* Finished a press: release it before the next one. */
	if (heldNow) {
		heldNow = 0;
		frameTimer = RELEASE_FRAMES - 1;
		return 0;
	}
	if (pendingMoves) {
		heldNow = 1 << (pendingMoves > 0 ? K_DOWN : K_UP);
		pendingMoves += pendingMoves > 0 ? -1 : 1;
		frameTimer = PRESS_FRAMES - 1;
		return heldNow;
	}
	if (tokenIndex >= running->nTokens) {
		running = NULL;
		return 0;
	}
	const struct Token* t = &running->tokens[tokenIndex++];
	switch (t->type) {
	case T_KEY:
		heldNow = 1 << t->value;
		frameTimer = PRESS_FRAMES - 1;
		return heldNow;
	case T_WAIT:
		frameTimer = t->value > 0 ? t->value - 1 : 0;
		return 0;
	case T_MENU:
		pendingMoves = _menuMoves(core, t->value);
		return 0;
	}
	return 0;
}

uint16_t dockUpdate(struct mCore* core, u32 held, u32 down, bool active) {
	if (flashFrames > 0) {
		--flashFrames;
	}
	if (!active) {
		running = NULL;
		heldNow = 0;
		return 0;
	}
	if (!running && (down & KEY_TOUCH)) {
		touchPosition pos;
		hidTouchRead(&pos);
		int hit = _hitTest(pos.px, pos.py);
		if (hit >= 0) {
			_startMacro(hit);
		}
	}
	UNUSED(held);
	if (!running) {
		return 0;
	}
	return _stepMacro(core);
}

static void _rect(u32 color, s16 x, s16 y, s16 w, s16 h) {
	ctrAddRectEx(color, x, y, w, h, 0, 0, 8, 8, 0);
}

void dockDraw(void) {
	if (!whiteReady || !dockFont) {
		return;
	}
	ctrActivateTexture(&whiteTex);
	_rect(COL_BG, 0, 0, 320, 240);
	_rect(COL_HEADER, 0, 0, 320, 24);
	_rect(COL_ACCENT, 0, 24, 320, 2);
	int i;
	for (i = 0; i < DOCK_BUTTONS; ++i) {
		const struct DockButton* b = &buttons[i];
		if (!b->nTokens) {
			continue;
		}
		bool lit = (i == pressedButton) && (running || flashFrames > 0);
		u32 color = b->small ? (lit ? COL_SMALL_HI : COL_SMALL) : (lit ? COL_MAIN_HI : COL_MAIN);
		_rect(color, b->x, b->y, b->w, b->h);
	}
	ctrFlushBatch();

	unsigned fh = GUIFontHeight(dockFont);
	GUIFontPrint(dockFont, 160, (24 + fh) / 2 - 1, GUI_ALIGN_HCENTER, COL_TEXT, "MONOMYTH DOCK");
	GUIFontPrint(dockFont, 4, (24 + fh) / 2 - 1, GUI_ALIGN_LEFT, COL_DIM, "build " MONOMYTH_BUILD);
	for (i = 0; i < DOCK_BUTTONS; ++i) {
		const struct DockButton* b = &buttons[i];
		if (!b->nTokens) {
			continue;
		}
		GUIFontPrint(dockFont, b->x + b->w / 2, b->y + (b->h + fh) / 2 - 2, GUI_ALIGN_HCENTER, COL_TEXT, b->label);
	}
	if (!(cursorAddr && actionsAddr && countAddr)) {
		GUIFontPrint(dockFont, 316, (24 + fh) / 2 - 1, GUI_ALIGN_RIGHT, COL_DIM, "guess");
	}
	ctrFlushBatch();
}
